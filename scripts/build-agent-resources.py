"""Compile maintained agent instructions for offline handoff and native hosts."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "scripts") not in sys.path:
    sys.path.insert(0, str(ROOT / "scripts"))
from build_release import host_skill_files, is_link


def body(relative: str) -> str:
    text = (ROOT / relative).read_text(encoding="utf-8").strip()
    if text.startswith("---\n"):
        text = text.split("---", 2)[2].strip()
    return text


def portable_role(skill: str) -> str:
    shared, separator, local = skill.partition("\n## VAS 프로젝트에서 추가로 확인할 사항\n")
    if not separator or not shared.strip() or not local.strip():
        raise ValueError("Each role needs shared instructions and a separate VAS section")
    return shared.rstrip()


def outputs() -> dict[str, str]:
    profiles = {}
    folder = ROOT / ".agents/skills/designer/references/profiles"
    for path in sorted(folder.glob("*.md")):
        relative = path.relative_to(ROOT).as_posix()
        text = body(relative)
        profiles[path.stem] = {
            "label": text.splitlines()[0].removeprefix("# "),
            "source": relative,
            "rules": [line[2:] for line in text.splitlines() if line.startswith("- ")],
        }
    roles = {role: body(f".agents/skills/{role}/SKILL.md")
             for role in ("implementer", "designer", "reviewer")}
    portable_roles = {role: portable_role(skill) for role, skill in roles.items()}
    workflow = body(".agents/HANDOFF-WORKFLOW.md") + "\n\n" + "\n\n".join(
        f"[ROLE INSTRUCTIONS: {role}]\n{instructions}" for role, instructions in roles.items())
    data = {
        "designer": portable_roles["designer"],
        "designAnalysis": body(".agents/skills/design-analysis/SKILL.md"),
        "workflow": workflow,
        "roles": roles,
        "portableRoles": portable_roles,
        "profiles": profiles,
    }
    encoded = json.dumps(data, ensure_ascii=False, indent=2)
    digest = hashlib.sha256(encoded.encode()).hexdigest()
    result = {
        "ui/agent-resources.js": "// Generated by scripts/build-agent-resources.py; SHA256: " + digest
        + "\nwindow.VASAgentResources = Object.freeze(" + encoded + ");\n",
        ".agents/agent-resources.json": encoded + "\n",
    }
    entrypoint = (ROOT / ".agents/PROJECT-ROOT.md").read_bytes().decode("utf-8")
    for filename in ("AGENTS.md", "CLAUDE.md", "GEMINI.md", ".cursorrules", ".windsurfrules"):
        result[filename] = entrypoint
    for role in ("implementer", "designer", "reviewer"):
        source = f".agents/skills/{role}/SKILL.md"
        raw = (ROOT / source).read_text(encoding="utf-8")
        description = next(line[13:] for line in raw.splitlines() if line.startswith("description: "))
        instructions = (
            "Follow the project root AGENTS.md. Build the user's app in src/ and use its own checks. "
            "The ui/ directory is VAS's interface. For a delegated task, use the parent's "
            "task type, target directory and scope; do not restart user onboarding. If the target "
            "is missing, ask the parent instead of guessing. Apply .agents/DEVELOPMENT.md only "
            "to VAS product development; otherwise follow the target project's rules.\n\n"
        ) + body(source)
        if role == "designer":
            instructions += "\n\n[DESIGN ANALYSIS]\n" + data["designAnalysis"]
        name = "vas_" + role
        toml = f'name = "{name}"\ndescription = {json.dumps(description, ensure_ascii=False)}\n'
        if role == "reviewer":
            toml += 'sandbox_mode = "read-only"\n'
        toml += "developer_instructions = " + json.dumps(instructions, ensure_ascii=False) + "\n"
        result[f".codex/agents/{name}.toml"] = toml
        # Omitted tool/model fields inherit the host's actual capabilities and permissions.
        result[f".claude/agents/{name}.md"] = (
            f"---\nname: vas-{role}\ndescription: {json.dumps(description, ensure_ascii=False)}\n"
            + ("tools: Read, Grep, Glob, WebFetch, WebSearch\n" if role == "reviewer" else "")
            + f"---\n\n{instructions}\n"
        )
    return result


def reject_linked_output(path: Path):
    for part in [path, *path.parents]:
        if part == ROOT:
            break
        if part.is_symlink() or (part.exists() and is_link(part)):
            raise RuntimeError(f"Linked agent output: {part.relative_to(ROOT)}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for relative, content in outputs().items():
        path = ROOT / relative
        reject_linked_output(path)
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content.replace("\r\n", "\n"):
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    for relative, source in host_skill_files():
        destination = ROOT / relative
        reject_linked_output(destination)
        content = source.read_bytes()
        if args.check:
            if not destination.is_file() or destination.read_bytes() != content:
                stale.append(relative.as_posix())
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
    if stale:
        print("Agent resources are stale: " + ", ".join(stale))
        return 1
    print("Agent resources " + ("verified" if args.check else "built"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
